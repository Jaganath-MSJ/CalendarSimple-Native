// Generates src/core/i18n/weekStartTable.ts from CLDR week data (cldr-core).
// Run: node scripts/gen-week-start.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const data = JSON.parse(
  readFileSync(require.resolve("cldr-core/supplemental/weekData.json"), "utf8"),
);
const { version } = JSON.parse(
  readFileSync(require.resolve("cldr-core/package.json"), "utf8"),
);
const DAY = { sun: 0, mon: 1, tue: 2, wed: 3, thu: 4, fri: 5, sat: 6 };

const entries = Object.entries(data.supplemental.weekData.firstDay)
  .filter(([region]) => region !== "001" && !region.includes("-alt-"))
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  .map(([region, day]) => {
    if (!(day in DAY)) throw new Error(`Unknown day ${day} for ${region}`);
    return `  ${region}: ${DAY[day]},`;
  });

const out = `/**
 * @file Region → first day of the week (0 = Sunday … 6 = Saturday).
 * Generated by scripts/gen-week-start.mjs from cldr-core ${version}
 * (supplemental/weekData.json, firstDay). Do not edit by hand.
 */
import type { WeekdayIndex } from "../types";

export const WEEK_START_FALLBACK: Readonly<Record<string, WeekdayIndex>> = {
${entries.join("\n")}
};
`;
writeFileSync(
  new URL("../src/core/i18n/weekStartTable.ts", import.meta.url),
  out,
);
console.log(`wrote ${entries.length} regions`);
